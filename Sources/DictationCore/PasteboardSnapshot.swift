import AppKit

/// Saves the pasteboard contents, puts dictated text on it, and puts the saved contents back.
///
/// The dictated text is marked as concealed and transient so clipboard managers skip it.
/// Restoring only happens when nobody else wrote to the pasteboard in the meantime; if the user
/// copied something during the paste delay, that copy wins.
public final class PasteboardSnapshot {
    public static let markerTypes: [NSPasteboard.PasteboardType] = [
        NSPasteboard.PasteboardType("org.nspasteboard.ConcealedType"),
        NSPasteboard.PasteboardType("org.nspasteboard.TransientType"),
        NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType"),
    ]

    private let pasteboard: NSPasteboard
    private var savedItems: [[NSPasteboard.PasteboardType: Data]] = []
    private var changeCountAfterWrite: Int?

    public init(pasteboard: NSPasteboard = .general) {
        self.pasteboard = pasteboard
    }

    /// Restoring stops copying once this many bytes are saved, so a large image on the clipboard
    /// does not hold up the paste.
    public static let maximumSavedBytes = 16 * 1024 * 1024

    /// Copies the items with their types, so text, rich text and small images survive.
    ///
    /// Promised data (files dragged from Finder, lazily rendered content) is skipped: reading it
    /// makes the source app produce it on the spot, which can take seconds.
    public func save() {
        var total = 0
        savedItems = (pasteboard.pasteboardItems ?? []).map { item in
            var types: [NSPasteboard.PasteboardType: Data] = [:]
            for type in item.types where !Self.isPromise(type) && total < Self.maximumSavedBytes {
                if let data = item.data(forType: type) {
                    types[type] = data
                    total += data.count
                }
            }
            return types
        }
    }

    static func isPromise(_ type: NSPasteboard.PasteboardType) -> Bool {
        let name = type.rawValue.lowercased()
        return name.contains("promise") || name.hasPrefix("dyn.")
    }

    /// Writes `text`, and formatted text as well when `rtf` is given.
    public func write(_ text: String, rtf: Data? = nil) {
        pasteboard.clearContents()
        let item = NSPasteboardItem()
        item.setString(text, forType: .string)
        if let rtf { item.setData(rtf, forType: .rtf) }
        for marker in Self.markerTypes { item.setData(Data(), forType: marker) }
        pasteboard.writeObjects([item])
        changeCountAfterWrite = pasteboard.changeCount
    }

    /// Puts the saved contents back whatever happened since `save`.
    public func restoreAlways() {
        pasteboard.clearContents()
        let items: [NSPasteboardItem] = savedItems.map { types in
            let item = NSPasteboardItem()
            for (type, data) in types { item.setData(data, forType: type) }
            return item
        }
        if !items.isEmpty { pasteboard.writeObjects(items) }
        changeCountAfterWrite = nil
    }

    public var changeCount: Int { pasteboard.changeCount }

    public var string: String? { pasteboard.string(forType: .string) }

    /// Returns false when the pasteboard changed since `write` and was therefore left alone.
    @discardableResult
    public func restore() -> Bool {
        guard let expected = changeCountAfterWrite, pasteboard.changeCount == expected else { return false }
        pasteboard.clearContents()
        let items: [NSPasteboardItem] = savedItems.map { types in
            let item = NSPasteboardItem()
            for (type, data) in types { item.setData(data, forType: type) }
            return item
        }
        if !items.isEmpty { pasteboard.writeObjects(items) }
        changeCountAfterWrite = nil
        return true
    }
}
